/**
 * CMS resource registry. Each resource maps a database table to an editable
 * form. Field names are the Drizzle property names of the table columns.
 * Publication status is never a form field: it changes only through the
 * workflow transitions in src/domain/editorial.ts.
 */
import type { PgTable } from "drizzle-orm/pg-core";
import * as s from "@/db/schema";
import { EVIDENCE_STATUSES, KNOWLEDGE_LAYERS, RESEARCH_STATUSES, ROLES } from "@/domain/editorial";

export type FieldType = "text" | "textarea" | "markdown" | "number" | "url" | "select" | "boolean" | "tags" | "ref";

export interface FieldDef {
  name: string;
  label: string;
  type: FieldType;
  required?: boolean;
  options?: readonly string[];
  /** For "ref": the resource whose records can be chosen. */
  ref?: string;
  help?: string;
}

/** Many-to-many links edited as a multi-select, stored in a join table. */
export interface RelationDef {
  name: string;
  label: string;
  target: string;
  table: PgTable;
  ownColumn: string; // property name on the join table pointing at this record
  otherColumn: string; // property name pointing at the target record
}

export interface ResourceDef {
  key: string;
  label: string;
  singular: string;
  table: PgTable;
  titleField: string;
  subtitleField?: string;
  slugField?: string;
  hasWorkflow: boolean;
  adminOnly?: boolean;
  canCreate?: boolean;
  publicPath?: (row: Record<string, unknown>) => string | null;
  fields: FieldDef[];
  relations?: RelationDef[];
  group: "Research" | "Objects" | "Curriculum" | "Library" | "People";
}

